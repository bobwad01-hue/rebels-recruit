// Exercise the actual TypeScript formatter so regressions in GPA and custom tokens fail the build.
const subjectExports={};
runInNewContext(ts.transpileModule(subjectFormat,{
 compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}
}).outputText,{exports:subjectExports});
const {buildRecruitingEmailSubject,formatRecruitingEmailGpa,validateRecruitingSubjectTemplate,hasUnresolvedRecruitingSubjectFields}=subjectExports;
assert.equal(formatRecruitingEmailGpa(4),'4.0');
assert.equal(formatRecruitingEmailGpa('3.5'),'3.5');
assert.equal(formatRecruitingEmailGpa('3.85'),'3.9');
assert.equal(formatRecruitingEmailGpa(''),'');
const sample={name:'Sara Smith',grad:2028,positions:'OF',throwBat:'R/R',gpa:4,college:'Buena Vista University',jersey:14};
assert.equal(buildRecruitingEmailSubject('Introduce Myself',sample),'Introduce Myself | Sara Smith | 2028 | OF/RHH | 4.0 GPA');
assert.equal(buildRecruitingEmailSubject('Introduce Myself',{...sample,gpa:3.5}),'Introduce Myself | Sara Smith | 2028 | OF/RHH | 3.5 GPA');
assert.equal(buildRecruitingEmailSubject('Introduce Myself',{...sample,gpa:''}),'Introduce Myself | Sara Smith | 2028 | OF/RHH | [GPA]');
assert.equal(buildRecruitingEmailSubject('Introduce Myself',sample,{subjectMode:'custom',customSubjectTemplate:'{{name}} | {{college}} | {{gpaLabel}}'}),'Sara Smith | Buena Vista University | 4.0 GPA');
assert.equal(buildRecruitingEmailSubject('Introduce Myself',sample,{subjectMode:'default',customSubjectTemplate:'{{name}}'}),'Introduce Myself | Sara Smith | 2028 | OF/RHH | 4.0 GPA');
assert.equal(buildRecruitingEmailSubject('[Subject]',{...sample,throwBat:''}),'[Subject] | Sara Smith | 2028 | OF/[Bats] | 4.0 GPA');
assert.equal(buildRecruitingEmailSubject('[Subject]',sample),'[Subject] | Sara Smith | 2028 | OF/RHH | 4.0 GPA');
assert.equal(hasUnresolvedRecruitingSubjectFields('[Subject] | Sara Smith | 2028 | OF/[Bats] | 4.0 GPA'),true);
assert.equal(hasUnresolvedRecruitingSubjectFields('Camp Follow-Up | Sara Smith | 2028 | OF/RHH | 4.0 GPA'),false);
assert.equal(validateRecruitingSubjectTemplate('{{topic}} | {{gpaLabel}}'),null);
assert.match(validateRecruitingSubjectTemplate('{{unknown}}'),/Unknown field/);
assert.match(validateRecruitingSubjectTemplate('Bad\nSubject'),/one line/);
