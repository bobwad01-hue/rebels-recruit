import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';

const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
function loadTs(path,deps={}){
 const js=ts.transpileModule(read(path),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
 const module={exports:{}};
 const fn=vm.runInNewContext('(function(exports,require,module){'+js+'\n})');
 fn(module.exports,name=>{if(!(name in deps))throw Error('Unknown dependency '+name);return deps[name]},module);
 return module.exports;
}
const formatter=loadTs('lib/recruiting-email-format.ts');
const {buildRecruitingEmailSignature,hasEmbeddedRecruitingSignature,withRecruitingEmailSignature}=loadTs('lib/recruiting-email-signature.ts',{'./recruiting-email-format':formatter});
const fields={name:'Maia Waddell',mobile:'8165551234',email:'maia@example.com',grad:'2028',sports:'https://example.com/maia',travelTeam:'KC Rebels',travelCoach:'Dan',travelCoachPhone:'8165559876',school:'Sample High',hsCity:'Independence',hsState:'MO',positions:'2B/OF',throwBat:'R/L',academic:'Biology'};
const standard=buildRecruitingEmailSignature(fields);
assert(standard.includes('Maia Waddell Profile Summary'));
assert(standard.includes('Mobile: 816-555-1234'));
assert(standard.includes('Travel Team: KC Rebels (Dan: 816-555-9876)'));
assert(standard.includes('High School: Sample High, Independence, MO'));
assert.equal(buildRecruitingEmailSignature(fields,{signatureMode:'none'}),'');
assert.equal(buildRecruitingEmailSignature(fields,{signatureMode:'custom',customSignature:'Thank you,\nMaia'}),'Thank you,\nMaia');
assert.equal(buildRecruitingEmailSignature(fields,{signatureMode:'none'},true),standard);
const added=withRecruitingEmailSignature('Hi Coach,\n\nA quick update.','<b>Hi Coach,</b><div>A quick update.</div>',standard);
assert.equal(added.added,true);
assert(added.body.endsWith(standard));
assert(added.bodyHtml.includes('<b>Hi Coach,</b>'));
assert(added.bodyHtml.includes('Maia Waddell Profile Summary'));
assert.equal(withRecruitingEmailSignature(added.body,added.bodyHtml,standard).added,false,'Signature must not be duplicated');
assert.equal(withRecruitingEmailSignature('Hi Coach,\n\n'+standard,'',standard).added,false);
assert.equal(hasEmbeddedRecruitingSignature('Old message\n\nMaia Waddell Profile Summary\nMobile: old number','New signature'),true,'Legacy saved templates must not gain a second profile footer');
assert.equal(withRecruitingEmailSignature('Hi','', '').body,'Hi','No signature mode must send unchanged body');
assert.equal(withRecruitingEmailSignature('Hi','', '').added,false);
const escaped=withRecruitingEmailSignature('Hi','<b>Hi</b>','Sincerely,\nA&B <C>');
assert(escaped.bodyHtml.includes('A&amp;B &lt;C&gt;'),'Custom signature must be escaped in formatted HTML');
assert(!escaped.bodyHtml.includes('A&B <C>'));
const quick=read('components/RecruitingQuickComposer.tsx');
const home=read('app/dashboard/page.tsx'),compose=read('app/compose-email/page.tsx');
assert(home.includes('<HomeWhereWeStand')&&home.includes('ph("/compose-email")')&&compose.includes('<RecruitingQuickComposer'), 'Home must show ranked recruiting snapshot while Compose retains signature-aware composer');
assert(quick.includes('aria-label="Email signature preview"'), 'Signature must be visible before sending');
assert(quick.includes('Automatically included when sent'));
assert(quick.includes('const prepared=withRecruitingEmailSignature(body,bodyHtml,emailSignature)'), 'Signature must be attached once on send');
assert(quick.includes('body:prepared.body,bodyHtml:prepared.bodyHtml'), 'Both plain and HTML email parts must include signature');
assert(quick.includes("if(id==='custom'){setSubject('');setBody('');return}"), 'Write My Own must preserve blank message editor');
assert(quick.includes('setBody([greeting,openingText,ask].filter(Boolean)'), 'Starter templates must not embed a duplicate signature');
assert(quick.includes('setBody(item.body);setBodyHtml'), 'Saved templates must remain editable and reusable');
assert(quick.includes('onSaved={next=>setProfile'), 'Changing signature preferences must refresh the preview without overwriting the draft');
console.log('Quick Compose automatic signature preview, custom/none modes, legacy drafts and Gmail MIME formatting checks passed.');
