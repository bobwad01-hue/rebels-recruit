-- RLTNL Recruiting: canonical coach identity and lossless merge audit.
-- Source of truth: one ACTIVE coach per normalized name and college.
-- Inactive/departed/retired historical staff records remain separate.

create table if not exists public.college_coach_identity_merges (
  id bigint generated by default as identity primary key,
  duplicate_coach_id uuid not null unique,
  canonical_coach_id uuid not null,
  college_id uuid not null,
  duplicate_record_before jsonb not null,
  canonical_record_before jsonb not null,
  dependent_rows_before jsonb not null default '{}'::jsonb,
  canonical_athlete_relationships_before jsonb not null default '[]'::jsonb,
  conflict_fields text[] not null default '{}'::text[],
  merged_at timestamptz not null default now(),
  merge_reason text not null default 'same_active_name_and_school'
);

create table if not exists public.college_coach_aliases (
  old_coach_id uuid primary key,
  canonical_coach_id uuid not null references public.college_coaches(id) on delete restrict,
  merge_audit_id bigint not null references public.college_coach_identity_merges(id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint college_coach_aliases_not_self check (old_coach_id <> canonical_coach_id)
);
create index if not exists college_coach_aliases_canonical_idx on public.college_coach_aliases(canonical_coach_id);

create table if not exists public.college_coach_contact_reviews (
  id bigint generated by default as identity primary key,
  coach_id uuid not null references public.college_coaches(id) on delete restrict,
  field_name text not null check (field_name in ('email','phone','x_url','instagram_url')),
  observed_values text[] not null,
  status text not null default 'pending' check (status in ('pending','verified','dismissed')),
  source_duplicate_coach_ids uuid[] not null default '{}'::uuid[],
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by uuid,
  resolution_note text,
  unique(coach_id,field_name)
);
create index if not exists college_coach_contact_reviews_status_idx on public.college_coach_contact_reviews(status,created_at desc);

alter table public.college_coach_identity_merges enable row level security;
alter table public.college_coach_aliases enable row level security;
alter table public.college_coach_contact_reviews enable row level security;

drop policy if exists college_coach_aliases_authenticated_read on public.college_coach_aliases;
create policy college_coach_aliases_authenticated_read on public.college_coach_aliases
  for select to authenticated using (true);

drop policy if exists college_coach_merges_super_owner_read on public.college_coach_identity_merges;
create policy college_coach_merges_super_owner_read on public.college_coach_identity_merges
  for select to authenticated using (
    exists (select 1 from public.platform_roles p where p.user_id=auth.uid() and p.role='super_owner')
  );

drop policy if exists college_coach_reviews_super_owner_read on public.college_coach_contact_reviews;
create policy college_coach_reviews_super_owner_read on public.college_coach_contact_reviews
  for select to authenticated using (
    exists (select 1 from public.platform_roles p where p.user_id=auth.uid() and p.role='super_owner')
  );

revoke all on public.college_coach_identity_merges from anon,authenticated;
revoke all on public.college_coach_aliases from anon,authenticated;
revoke all on public.college_coach_contact_reviews from anon,authenticated;
grant select on public.college_coach_aliases to authenticated;
grant select on public.college_coach_identity_merges to authenticated;
grant select on public.college_coach_contact_reviews to authenticated;

create or replace function public.prevent_duplicate_active_college_coach()
returns trigger language plpgsql set search_path=public as $$
declare existing_coach uuid;
declare identity_key text;
begin
  if new.lifecycle_status is distinct from 'active'
     or new.college_id is null
     or nullif(btrim(new.first_name),'') is null
     or nullif(btrim(new.last_name),'') is null then
    return new;
  end if;

  if tg_op='UPDATE'
     and new.college_id is not distinct from old.college_id
     and lower(btrim(new.first_name)) is not distinct from lower(btrim(old.first_name))
     and lower(btrim(new.last_name)) is not distinct from lower(btrim(old.last_name))
     and new.lifecycle_status is not distinct from old.lifecycle_status then
    return new;
  end if;

  identity_key:=new.college_id::text||':'||lower(btrim(new.first_name))||':'||lower(btrim(new.last_name));
  perform pg_advisory_xact_lock(hashtextextended(identity_key,0));

  select cc.id into existing_coach
  from public.college_coaches cc
  where cc.college_id=new.college_id
    and cc.lifecycle_status='active'
    and lower(btrim(cc.first_name))=lower(btrim(new.first_name))
    and lower(btrim(cc.last_name))=lower(btrim(new.last_name))
    and cc.id is distinct from new.id
  limit 1;

  if existing_coach is not null then
    raise exception using
      errcode='23505',
      message='This coach is already listed at this school. Use the existing coach record instead of creating another.',
      hint='Existing coach ID: '||existing_coach::text;
  end if;
  return new;
end;
$$;
